    /**
     * An empty or blank API key is rejected at construction. Published 1.0.1 stored the
     * empty string and sent it as `X-API-Key`, so the mistake surfaced as a 401 on the
     * first request. The remaining defaults are pinned by `FeedbackKitConfigTest`.
     */
    @Test
    fun `an empty api key is rejected at construction`() {
        try {
            FeedbackKitConfig(apiKey = "")
            fail("An empty API key was accepted")
        } catch (error: IllegalArgumentException) {
            assertTrue(error.message.orEmpty().contains("API key"))
        }
        try {
            FeedbackKitConfig(apiKey = "   ")
            fail("A blank API key was accepted")
        } catch (error: IllegalArgumentException) {
            assertTrue(error.message.orEmpty().contains("API key"))
        }
    }

    // MARK: -20 · theme

    /**
     * `-20` ⚠️ RECORDED — the two "shared-palette" SDKs disagree on light mode.
     *
     * Kotlin's shipped light theme is pinned verbatim below: white background,
     * `0xFFF9FAFB` card, `0xFF1F2937` text. Flutter ships the same palette with background
     * and card **swapped** (`0xFFF9FAFB` background, white card) and text `0xFF111827` —
     * so the same app on the two platforms renders light mode with inverted surfaces.
     * Which side is canonical is a product decision; this pins Kotlin's half so the
     * eventual reconciliation flips a named test rather than drifting silently.
     */
    @Test
    fun `the shipped light theme values are pinned verbatim`() {
        val light = FeedbackKitTheme.Light
        assertEquals(Color(0xFFFFFFFF), light.backgroundColor)
        assertEquals(Color(0xFFF9FAFB), light.cardBackgroundColor)
        assertEquals(Color(0xFF1F2937), light.textColor)
    }

    /**
     * Both presets exist, and dark's surface stack is pinned so a palette edit on either
     * side of the light/dark pair reddens a named case.
     */
    @Test
    fun `the dark preset exists and its surface stack is pinned`() {
        assertNotNull(FeedbackKitTheme.Light)
        assertNotNull(FeedbackKitTheme.Dark)

        val dark = FeedbackKitTheme.Dark
        assertEquals(Color(0xFF60A5FA), dark.primaryColor)
        assertEquals(Color(0xFF111827), dark.backgroundColor)
        assertEquals(Color(0xFF1F2937), dark.cardBackgroundColor)
        assertEquals(Color(0xFF374151), dark.borderColor)
    }

    /**
     * An unknown 4xx stays `UnknownError` (no new sealed case) and keeps the real status,
     * so a host can tell 422 from a failure that never had one. 429 stays `RateLimitError`.
     */
    @Test
    fun `an unknown 4xx keeps its status code`() {
        val validation = FeedbackKitError.fromStatusCode(422, "Validation failed")
        val rateLimited = FeedbackKitError.fromStatusCode(429, "Too many requests")

        assertTrue(validation is FeedbackKitError.UnknownError)
        assertEquals(422, validation.statusCode)
        assertEquals("UNKNOWN", validation.code)

        // The re-anchored half: no longer discarded.
        assertTrue(rateLimited is FeedbackKitError.RateLimitError)
        assertEquals(429, rateLimited.statusCode)
    }

    /**
     * ⚠️ RECORDED AS SHIPPED — `merge` discards its receiver entirely.
     *
     * `FeedbackKitTheme.merge(other)` is documented as "Merge this theme with another" and
     * is implemented as `= other`: every receiver-side customization is thrown away, so a
     * partial override object replaces the whole theme with defaults instead of layering.
     * A real merge would need per-field defaulting; until that lands, this pins the
     * shipped identity so a fix flips a named test.
     */
    @Test
    fun `merge returns the other theme verbatim, discarding the receiver`() {
        val customized = FeedbackKitTheme.Dark
        val override = FeedbackKitTheme(primaryColor = Color(0xFFEF4444))

        val merged = customized.merge(override)

        assertEquals(override, merged)
        // The receiver's dark background is gone — replaced by `override`'s default white.
        assertEquals(Color(0xFFFFFFFF), merged.backgroundColor)
    }
